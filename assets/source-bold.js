  const findOccurrence = (text, phrase, occurrence = 1) => {
    let start = -1;
    let searchFrom = 0;
    for (let index = 0; index < occurrence; index += 1) {
      start = text.indexOf(phrase, searchFrom);
      if (start < 0) return -1;
      searchFrom = start + phrase.length;
    }
    return start;
  };

  const applySourceBold = (element) => {
    const id = element.dataset.id;
    const mapped = sourceBoldMap[id];

    if (mapped?.full) {
      element.style.fontWeight = "700";
      element.dataset.sourceBoldFull = "true";
      return;
    }

    const phrases = mapped?.phrases || (
      element.dataset.boldPhrase
        ? [{
            text: element.dataset.boldPhrase,
            occurrence: Number(element.dataset.boldOccurrence || "1"),
          }]
        : []
    );
    if (!phrases.length) return;
    const existingEmphasis = element.querySelectorAll(
      "strong[data-source-bold], strong[data-vocabulary-term]"
    );
    if (existingEmphasis.length === phrases.length) return;

    const text = element.textContent;
    const ranges = phrases.map((entry) => {
      const phrase = typeof entry === "string" ? entry : entry.text;
      const occurrence = typeof entry === "string" ? 1 : (entry.occurrence || 1);
      const start = findOccurrence(text, phrase, occurrence);
      return { start, end: start + phrase.length, phrase };
    }).filter(({ start }) => start >= 0).sort((a, b) => a.start - b.start);

    if (!ranges.length) return;
    const fragment = document.createDocumentFragment();
    let cursor = 0;
    ranges.forEach(({ start, end, phrase }) => {
      if (start < cursor) return;
      fragment.append(document.createTextNode(text.slice(cursor, start)));
      const strong = document.createElement("strong");
      strong.dataset.sourceBold = "true";
      strong.textContent = phrase;
      fragment.append(strong);
      cursor = end;
    });
    fragment.append(document.createTextNode(text.slice(cursor)));
    element.replaceChildren(fragment);
  };

  const applyAllSourceBold = () => {
    document.querySelectorAll("[data-id], [data-bold-phrase]").forEach(applySourceBold);
  };

  const observer = new MutationObserver(() => {
    observer.disconnect();
    applyAllSourceBold();
    observer.observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true,
    });
  });

  applyAllSourceBold();
  observer.observe(document.body, {
    childList: true,
    subtree: true,
    characterData: true,
  });
